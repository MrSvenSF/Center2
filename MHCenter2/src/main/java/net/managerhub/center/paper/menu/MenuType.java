package net.managerhub.center.paper.menu;

/** The menus MHCenter2 can open. */
public enum MenuType {

    /** The normal info menu. */
    CENTER_INFO,

    /** The administrative menu behind the admin button. */
    CENTER_ADMIN,

    /** The network status of the MHCenter2 instances. */
    SERVER_STATUS,

    /** The detail view of one module, opened from the module row of the admin menu. */
    MODULE_DETAIL
}
